-- 未发布草稿的「安装级配置」。
--
-- 为什么草稿也需要这份配置：本地草稿启用之后就是这个空间真正在用的插件
-- （和已安装件一样进检索池、进工具列表、起常驻进程），但配置一直只存在于
-- plugin_install 上。于是草稿永远拿到空配置：wa.config() 只有清单默认值，
-- 需要 AppKey 之类的插件（钉钉机器人、MCP 服务地址、审批档位）在草稿态一律
-- 「未就绪」——作者必须先发布、安装，才能填自己写的插件要用的参数，
-- 而这恰恰是本机联调最需要跳过的一步。
--
-- 互斥语义不变：同一 slug 的本地目录与安装记录互斥，所以两条记录不会同时
-- 存在；读取时安装记录优先，只是兜底顺序，不是「两处同时生效」。
alter table plugin_candidate add column if not exists config jsonb not null default '{}'::jsonb;
